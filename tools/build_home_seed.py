#!/usr/bin/env python3
"""Build a deterministic checked factory home, embedded as a bounded zlib stream."""
import argparse
import hashlib
import json
import shutil
from pathlib import Path
import subprocess
import tempfile
import zlib
from create_state import create
from check_state import check_header

ROOT = Path(__file__).resolve().parents[1]


def build(output):
    output = Path(output)
    inputs = [ROOT / 'tools/create_state.py', ROOT / 'tools/check_state.py', Path(__file__)]
    versions = {}
    for name in ('mke2fs','debugfs','e2fsck'):
        command = shutil.which(name) or '/sbin/' + name
        result = subprocess.run([command,'-V'],check=True,text=True,capture_output=True)
        versions[name] = (result.stdout + result.stderr).strip()
    fingerprint = hashlib.sha256(b''.join(p.read_bytes() for p in inputs) +
                                 json.dumps(versions,sort_keys=True).encode()).hexdigest()
    report_path = output / 'home-seed.json'
    header_path = output / 'home_seed.h'
    if report_path.exists() and header_path.exists():
        report = json.loads(report_path.read_text())
        if (report.get('source_sha256') == fingerprint and
                report.get('header_sha256') == hashlib.sha256(header_path.read_bytes()).hexdigest()):
            return report
    output.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='gaijin-factory-') as temporary:
        image = create(Path(temporary) / 'factory.ext2', 32, factory=True)
        check_header(image)
        raw_hash, compressed = hashlib.sha256(), bytearray()
        compressor = zlib.compressobj(9)
        with image.open('rb') as stream:
            for chunk in iter(lambda: stream.read(65536), b''):
                raw_hash.update(chunk)
                compressed.extend(compressor.compress(chunk))
        compressed.extend(compressor.flush())
        # Independent decoder round trip, with an explicit output bound.
        decoder = zlib.decompressobj()
        expanded = decoder.decompress(compressed, 32*1024*1024+1)
        if len(expanded) != 32*1024*1024 or not decoder.eof or decoder.unused_data:
            raise ValueError('factory compression round trip failed')
        if hashlib.sha256(expanded).digest() != raw_hash.digest():
            raise ValueError('factory compressed content differs')
        del expanded
    def array(name, payload):
        lines = [','.join(f'0x{v:02x}' for v in payload[n:n+16]) for n in range(0,len(payload),16)]
        return f'static const unsigned char {name}[] = {{\n' + ',\n'.join(lines) + '\n};\n'
    header = ('// Generated by tools/build_home_seed.py; do not edit.\n#pragma once\n' +
              '#define GH_SEED_ID "Gaijin home template v1"\n' +
              array('gh_seed_zlib', compressed) + array('gh_seed_hash', raw_hash.digest()))
    header_path.write_text(header)
    report = dict(format=1, capacity_bytes=32*1024*1024, compression='zlib',
                  compressed_bytes=len(compressed), expanded_sha256=raw_hash.hexdigest(),
                  compressed_sha256=hashlib.sha256(compressed).hexdigest(),
                  source_sha256=fingerprint, header_sha256=hashlib.sha256(header.encode()).hexdigest(),
                  layout='gaijin-state-v1', setup='gaijin-setup-v1', host_fsck='PASS')
    report['host_tools'] = versions
    report_path.write_text(json.dumps(report, indent=2)+'\n')
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/home')
    args = parser.parse_args()
    try:
        print(json.dumps(build(args.output), indent=2))
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        parser.exit(1, f'Factory seed failed: {exc}\n')
